package com.aether.weather.data.model

/**
 * Open-Meteo отдаёт погоду WMO-кодами вместо текстовых иконок OpenWeather.
 * Чтобы не переписывать палитры, иконки и звуки (они завязаны на строки вида
 * "10d"/"01n"), маппим WMO-код + день/ночь в тот же формат.
 *
 * Справочник WMO: https://open-meteo.com/en/docs (weather_code)
 */
fun wmoToIcon(code: Int, isDay: Boolean): String {
    val group = when (code) {
        0 -> "01"                     // ясно
        1 -> "02"                     // преимущественно ясно
        2 -> "03"                     // переменная облачность
        3 -> "04"                     // пасмурно
        45, 48 -> "50"                // туман
        51, 53, 55 -> "09"            // морось
        56, 57 -> "09"                // ледяная морось
        61, 63, 65 -> "10"            // дождь
        66, 67 -> "10"                // ледяной дождь
        71, 73, 75, 77 -> "13"        // снег
        80, 81, 82 -> "09"            // ливни
        85, 86 -> "13"               // снегопад
        95, 96, 99 -> "11"            // гроза
        else -> "04"
    }
    return group + if (isDay) "d" else "n"
}

